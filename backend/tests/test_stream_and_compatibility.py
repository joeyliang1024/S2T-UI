@pytest.mark.asyncio
async def test_summary_first_delta_and_disconnect_release(environment):
    environment.update(
        S2T_SUMMARY_ENDPOINT="http://model/v1",
        S2T_SUMMARY_MODEL="mock",
        S2T_SUMMARY_API_KEY="secret",
    )
    closed, delivered, disconnected = asyncio.Event(), asyncio.Event(), asyncio.Event()

    class Stream(httpx.AsyncByteStream):
        async def __aiter__(self):
            yield b'data: {"choices":[{"delta":{"content":"first"}}]}\n\n'
            await asyncio.Event().wait()

        async def aclose(self):
            closed.set()

    async def upstream(request):
        await request.aread()
        return httpx.Response(200, stream=Stream(), headers={"content-type": "text/event-stream"})

    app = create_app(environment, httpx.MockTransport(upstream))
    async with app.router.lifespan_context(app):
        rt = app.state.runtime
        user = await rt.auth.login({"username": "admin", "password": "admin"})
        body = json.dumps(
            {"messages": [{"role": "user", "content": "hello"}], "stream": True}
        ).encode()
        received = False

        async def receive():
            nonlocal received
            if not received:
                received = True
                return {"type": "http.request", "body": body, "more_body": False}
            await disconnected.wait()
            return {"type": "http.disconnect"}

        async def send(message):
            if message["type"] == "http.response.body" and b'"delta"' in message.get("body", b""):
                delivered.set()

        scope = {
            "type": "http",
            "app": app,
            "asgi": {"version": "3.0", "spec_version": "2.3"},
            "http_version": "1.1",
            "method": "POST",
            "scheme": "http",
            "path": "/api/summaries",
            "raw_path": b"/api/summaries",
            "query_string": b"",
            "headers": [
                (b"authorization", ("Bearer " + rt.auth.issue(user)).encode()),
                (b"content-type", b"application/json"),
            ],
            "server": ("test", 80),
            "client": ("test", 1),
        }
        task = asyncio.create_task(app(scope, receive, send))
        try:
            await asyncio.wait_for(delivered.wait(), 2)
            assert not task.done()
            disconnected.set()
            await asyncio.wait_for(task, 2)
            assert closed.is_set()
            assert rt.admission.gates["summary"].semaphore._value == 4
        finally:
            if not task.done():
                task.cancel()
                await asyncio.gather(task, return_exceptions=True)


def test_legacy_bcrypt_jwt_and_aes_data_compatibility(client, admin):
    from pathlib import Path

    # Fixed legacy-format vectors generated by the retired Node implementation.
    # No Node packages or executable are needed to exercise data compatibility.
    fixture = json.loads((Path(__file__).parent / "fixtures/legacy-auth.json").read_text())
    rt = client.app.state.runtime
    rt.auth.secret = fixture["secret"]
    import bcrypt

    assert bcrypt.checkpw(b"old-password", fixture["hash"].encode())
    assert rt.auth.decrypt(fixture["credential"]) == "legacy-api-key"
    import jwt

    assert (
        jwt.decode(fixture["token"], fixture["secret"], algorithms=["HS256"])["sub"]
        == fixture["id"]
    )


@pytest.mark.asyncio
async def test_model_cookie_jar_never_crosses_accounts(environment):
    requests = []

    async def handler(request):
        requests.append(request)
        return httpx.Response(
            200, headers={"set-cookie": "session=upstream-user; Path=/"}, json={"ok": True}
        )

    from app.main import StatelessClient

    async with StatelessClient(transport=httpx.MockTransport(handler)) as client:
        await client.get("http://model/v1")
        await client.get("http://model/v1")
    assert all("cookie" not in request.headers for request in requests)
