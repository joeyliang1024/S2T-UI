const assert = require('node:assert/strict')
const { createAdaptiveCapacity } = require('../../server/adaptive-capacity.cjs')
const delay = ms => new Promise(resolve => setTimeout(resolve, ms))
;(async () => {
  let clock = 0
  const capacity = createAdaptiveCapacity({ maximum: 8, now: () => clock, idleMs: 15 })
  const first = await capacity.acquire(), waiting = capacity.acquire()
  clock = 1; first()
  const releaseWaiting = await waiting
  assert.equal(capacity.stats().limit, 1, 'a burst alone cannot raise the connection ceiling')
  releaseWaiting()
  clock = 1000
  const one = await capacity.acquire(), twoPending = capacity.acquire()
  clock = 1001; one()
  const two = await twoPending
  assert.equal(capacity.stats().limit, 2, 'healthy sustained demand grows by one per interval')
  const other = await capacity.acquire()
  other(new Error('backend timeout'))
  assert.equal(capacity.stats().limit, 1, 'an error immediately halves the limit')
  assert.equal(capacity.stats().active, 1, 'shrinking never cancels an active operation')
  two()
  clock = 2000
  const cooldown = await capacity.acquire(), pending = capacity.acquire()
  clock = 2001; cooldown(); (await pending)()
  assert.equal(capacity.stats().limit, 1, 'cooldown prevents rapid regrowth')
  await delay(20)
  assert.equal(capacity.stats().limit, 1)
  capacity.close()
  await assert.rejects(capacity.acquire(), /closed/)
  const bounded = createAdaptiveCapacity({ maximum: 1, waitMs: 10, maxWaiting: 1 })
  const held = await bounded.acquire()
  const expires = assert.rejects(bounded.acquire(), /timed out/)
  await assert.rejects(bounded.acquire(), /queue full/)
  await expires; held(); bounded.close()
  let failureClock = 10000
  const storm = createAdaptiveCapacity({ minimum: 2, maximum: 16, initial: 16, now: () => failureClock, waitMs: 10 })
  const operations = await Promise.all(Array.from({ length: 16 }, () => storm.acquire()))
  for (const release of operations) release(new Error('same outage'))
  assert.equal(storm.stats().limit, 8, 'one failure storm halves once instead of collapsing to minimum')
  failureClock += 6000
  const busy = await Promise.all(Array.from({ length: 8 }, () => storm.acquire()))
  await assert.rejects(storm.acquire(), /timed out/)
  assert.equal(storm.stats().limit, 8, 'local admission timeout does not reduce healthy backend capacity')
  for (const release of busy) release()
  storm.close()
  console.log('PASS bounded adaptive connections: additive growth, immediate decrease, cooldown, idle shrink, queue expiry and no transaction cancellation')
})().catch(error => { console.error(error); process.exitCode = 1 })
