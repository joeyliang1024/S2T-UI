const assert = require('node:assert/strict')
const { mkdtemp, rm } = require('node:fs/promises')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const { LocalConfigStore, LocalBlobStore } = require('../../server/storage/local.cjs')
const { RecordingChunks } = require('../../server/recording-chunks.cjs')
const { executeIdempotent } = require('../../server/idempotency.cjs')
const { createSharedLimits } = require('../../server/shared-limits.cjs')
const delay = ms => new Promise(resolve => setTimeout(resolve, ms))
;(async () => {
  const root = await mkdtemp(join(tmpdir(), 's2t-scale-local-'))
  try {
    const a = new LocalConfigStore(root), b = new LocalConfigStore(root)
    const input = { id: 'job-1', userId: 'user-1', sessionId: 'session-1', audioKey: 'audio-1', payload: { processingToken: 'intent-1' } }
    await a.put('user-1', 'sessions', { version: 1, sessions: [{ id: 'session-1' }] })
    await a.enqueueDiarizationJob(input)
    const lease = await a.claimDiarizationJob('owner-1')
    await b.enqueueDiarizationJob({ ...input, id: 'duplicate' })
    assert.equal((await b.getDiarizationJob('user-1', lease.id)).state, 'running', 'duplicate intent must not reset a live job')
    assert.equal(await b.commitDiarizationJob(lease.id, 'owner-1', lease.leaseGeneration, 'user-2', 1, {}), 'lost')
    assert.equal(await b.commitDiarizationJob(lease.id, 'owner-1', lease.leaseGeneration, 'user-1', 0, {}), 'conflict')
    const outcomes = await Promise.all([a, b].map(store => store.commitDiarizationJob(lease.id, 'owner-1', lease.leaseGeneration, 'user-1', 1, { version: 2, sessions: [] })))
    assert.equal(outcomes.filter(value => value === 'committed').length, 1)
    assert.equal((await a.getDiarizationJob('user-1', lease.id)).state, 'completed')
    await b.enqueueDiarizationJob({ ...input, payload: { processingToken: 'intent-2' } })
    const stale = await b.claimDiarizationJob('owner-1')
    await a.update('diarization-system', 'jobs', value => ({ jobs: value.jobs.map(job => ({ ...job, leaseUntil: Date.now() - 1 })) }))
    assert.equal(await b.commitDiarizationJob(stale.id, 'owner-1', stale.leaseGeneration, 'user-1', 2, { version: 3 }), 'lost')
    assert.equal((await a.get('user-1', 'sessions')).version, 2)
    let calls = 0
    const operation = () => { calls++; return delay(30).then(() => ({ text: 'same' })) }
    const first = executeIdempotent(a, 'user-1', 'asr', 'segment-1', 'hash', operation)
    await delay(10)
    await assert.rejects(executeIdempotent(b, 'user-1', 'asr', 'segment-1', 'hash', operation), error => error.status === 409)
    await first
    assert.deepEqual(await executeIdempotent(b, 'user-1', 'asr', 'segment-1', 'hash', operation), { text: 'same' })
    assert.equal(calls, 1)
    await assert.rejects(executeIdempotent(a, 'user-1', 'asr', 'segment-1', 'different', operation), error => error.status === 409)
    await executeIdempotent(a, 'user-2', 'asr', 'segment-1', 'different', operation)
    const blob = new LocalBlobStore(root)
    const one = new RecordingChunks({ config: a, blob }), two = new RecordingChunks({ config: b, blob })
    const pcm = Buffer.from([1, 0, 2, 0])
    assert.equal((await one.append('user-1', 'capture-1', 1, 2, 16000, pcm)).persistedSamples, 0)
    assert.equal((await two.append('user-1', 'capture-1', 0, 0, 16000, pcm)).persistedSamples, 4)
    assert.equal((await one.append('user-1', 'capture-1', 0, 0, 16000, pcm)).contiguousChunks, 2)
    await assert.rejects(two.append('user-1', 'capture-1', 0, 0, 16000, Buffer.from([3, 0])), error => error.status === 409)
    await assert.rejects(one.finish('user-1', 'capture-1', 1, 2), error => error.status === 409)
    assert.equal(await two.status('user-2', 'capture-1'), null)
    await one.finish('user-1', 'capture-1', 2, 4)
    const audio = await blob.get('user-1', 'audio/capture-1')
    assert.equal(audio.readUInt32LE(40), 8)
    assert.deepEqual(audio.subarray(44), Buffer.concat([pcm, pcm]))
    assert.equal((await two.finish('user-1', 'capture-1', 2, 4)).durable, true)
    const failing = new RecordingChunks({ config: a, blob: { put: async () => { throw new Error('outage') } } })
    await assert.rejects(failing.append('user-1', 'capture-fail', 0, 0, 16000, pcm))
    assert.equal(await one.status('user-1', 'capture-fail'), null, 'failed persistence must not ACK')
    const limiter = createSharedLimits({}, { asr: 2 })
    assert.equal((await limiter.accept('user', 'asr')).accepted, true)
    assert.equal((await limiter.accept('user', 'asr')).accepted, true)
    assert.equal((await limiter.accept('user', 'asr')).accepted, false)
    await limiter.health(); await limiter.close()
    console.log('PASS: standalone defaults, atomic task commit, generation fencing, deduplication, durable chunks, gap detection and failed-write ACK safety')
  } finally { await rm(root, { recursive: true, force: true }) }
})().catch(error => { console.error(error); process.exitCode = 1 })
