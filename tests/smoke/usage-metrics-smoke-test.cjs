const assert = require('node:assert/strict')
const usage = require('../../server/usage-metrics.cjs')
usage.registerUser({id:'a',NT:'測試甲',Department:'研發部'})
usage.registerUser({id:'b',NT:'測試乙',Department:'營運部'})
usage.observeRequest(null, 'transcriptions', 200, 1)
usage.observeRequest('a', 'transcriptions', 200, .5)
usage.observeRequest('a', 'transcriptions', 200, .2, true)
usage.observeRequest('b', 'audio/arbitrary-secret-key', 403, .1)
usage.observeRequest('b', 'unknown/private/transcript', 500, .1)
usage.observeExecution('a', 'translations', { input: '🚀文', output: '字', usage: { prompt_tokens: -1, completion_tokens: 4 } })
usage.observeExecution('a', 'translations', { input: '', output: '', usage: { prompt_tokens: 0, completion_tokens: 0 } })
usage.observeExecution('a', 'transcriptions', { audio: Buffer.from('non-wav') })
const raw = usage.render()
assert.match(raw, /s2t_user_requests_total\{user_id="a",nt="測試甲",department="研發部",operation="transcriptions",outcome="aborted"\} 1/)
assert.match(raw, /s2t_user_input_characters_total\{user_id="a",nt="測試甲",department="研發部",operation="translations"\} 2/)
assert.match(raw, /s2t_user_token_usage_missing_total\{user_id="a",nt="測試甲",department="研發部",operation="translations"\} 1/)
assert.match(raw, /s2t_user_input_tokens_total\{user_id="a",nt="測試甲",department="研發部",operation="translations"\} 0/)
assert.match(raw, /s2t_user_audio_duration_unknown_total\{user_id="a",nt="測試甲",department="研發部",operation="transcriptions"\} 1/)
assert.ok(!raw.includes('private/transcript') && !raw.includes('arbitrary-secret-key'))
assert.equal(usage.wavSeconds(Buffer.alloc(44)), null)
const truncated = Buffer.alloc(20); truncated.write('RIFF');truncated.write('WAVE',8);truncated.write('data',12);truncated.writeUInt32LE(1000,16)
assert.equal(usage.wavSeconds(truncated), null)
assert.ok(!raw.includes('user_id="null"'))
console.log('PASS unauthenticated omission, bounded route labels, abort outcomes, Unicode counts, invalid token usage and unknown/truncated audio duration')
